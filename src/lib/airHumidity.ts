// airHumidity.ts — плотность влажного рудничного воздуха.
//
// НОРМАТИВ: «Проведение воздушно-депрессионных и газовых съёмок, определение
// устойчивости проветривания горных выработок…» (МЧС России, 2014),
// приложение 9, п. 9.2.
//
//   ρ = (3,48·P − 0,0038·φ·P_нас) / (273 + t)          (9.2)
//
//   ρ     — плотность воздуха, кг/м³;
//   P     — абсолютное давление, кПа;
//   φ     — относительная влажность, %;
//   P_нас — давление насыщенного водяного пара при t, кПа (таблица 9.2);
//   t     — температура воздуха, °C.
//
// Без влажности (φ = 0) формула вырождается в 9.1: ρ = 3,48·P / (273 + t).
//
// КОГДА НУЖНО. Норматив требует учитывать влажность при разности абсолютных
// отметок замерных станций более 100 м (пп. 69, 72, 99) — то есть в стволах и
// глубоких наклонных выработках, где вес столба воздуха формирует естественную
// тягу. Влажный воздух ЛЕГЧЕ сухого при той же температуре (водяной пар легче
// воздуха), поэтому влажность уменьшает плотность и меняет тягу.

/** Стандартное атмосферное давление на уровне моря, кПа */
export const P_STD_KPA = 101.325;

/** Влажность по умолчанию для узлов внутри шахты, % (рудничный воздух влажный) */
export const DEFAULT_MINE_HUMIDITY = 85;

/** Влажность по умолчанию на поверхности, % */
export const DEFAULT_SURFACE_HUMIDITY = 60;

/**
 * Давление насыщенного водяного пара, кПа, по температуре t (°C).
 * Формула Магнуса — Тетенса:  P_нас = 0,61094·exp(17,625·t / (t + 243,04)).
 *
 * ПОЧЕМУ ФОРМУЛА, А НЕ ТАБЛИЦА 9.2. Таблица норматива задана шагом 5 °C в
 * диапазоне −20…+30 °C. Формула Магнуса воспроизводит ВСЕ её значения с
 * точностью до сотых (проверено по каждой точке таблицы) и при этом работает
 * непрерывно и за пределами диапазона — что нужно при пожаре, где температура
 * струи достигает сотен градусов.
 */
export function saturationPressureKPa(tempC: number): number {
  // Ограничение снизу — лёд, сверху — кипение: за этими пределами
  // формула теряет смысл, а в расчёте такие значения не встречаются.
  const t = Math.max(-60, Math.min(200, tempC));
  return 0.61094 * Math.exp((17.625 * t) / (t + 243.04));
}

/**
 * Плотность влажного воздуха по формуле 9.2 норматива, кг/м³.
 *
 * @param tempC      температура воздуха, °C
 * @param humidityPc относительная влажность, % (0…100)
 * @param pressureKPa абсолютное давление, кПа (по умолчанию стандартное)
 */
export function humidAirDensity(
  tempC: number,
  humidityPc: number,
  pressureKPa: number = P_STD_KPA,
  useHumidity: boolean = true,
): number {
  // Верхняя граница температуры — 1200 °C: при пожаре струя раскаляется до
  // сотен градусов, и обрезка ниже занижала бы тепловую тягу.
  const t   = Math.max(-60, Math.min(1200, tempC));
  // ОБРАТНАЯ СОВМЕСТИМОСТЬ. Прежняя формула ρ = 353/(273+t) отвечает давлению
  // 353/3,48 = 101,44 кПа, а не стандартным 101,325 — расхождение 0,11 %.
  // Поэтому при выключенном учёте возвращаем ровно прежнюю формулу, иначе у
  // всех существующих проектов результаты сдвинулись бы без ведома пользователя.
  if (!useHumidity) return 353.0 / (273.0 + t);
  const phi = Math.max(0, Math.min(100, humidityPc));
  const P   = Math.max(1, pressureKPa);
  // ГРАНИЦА ПРИМЕНИМОСТИ. Таблица 9.2 норматива задана на −20…+30 °C. Выше
  // 100 °C давление насыщенного пара превышает атмосферное (при 400 °C — в
  // 350 раз), понятие относительной влажности теряет смысл, и формула 9.2
  // начинает выдавать бессмыслицу: проверка дала «депрессию» в 30 раз выше
  // реальной. Физический предел — парциальное давление пара не может
  // превышать полное давление смеси, поэтому ограничиваем его сверху.
  const pn = Math.min(saturationPressureKPa(t), P);
  const rho = (3.48 * P - 0.0038 * phi * pn) / (273.0 + t);
  // Плотность не может стать нулевой или отрицательной ни при каких входных
  // данных, но страхуемся от деления на ноль в потребителях.
  return rho > 0.05 ? rho : 0.05;
}

// ПРИМЕЧАНИЕ. Барометрической поправки давления по глубине здесь намеренно НЕТ.
// В расчёте естественной тяги плотности рудничного и наружного столбов должны
// сравниваться при ОДНОМ давлении: иначе при полной изотермии (температура в
// шахте равна наружной) возникает тяга из ничего — вес самого столба воздуха в
// сеточной форме уже учтён разностью высотных отметок.