//   • в web-версии     — облачная функция airflow;
//   • в desktop-версии — тот же самый файл, запущенный локальным сервером
//     внутри программы (скрипты desktop/prepare.* копируют backend/airflow
//     в сборку как есть, без изменений).
// Поэтому настольная программа и браузер считают буквально одним кодом, и
// расхождение результатов между ними невозможно по построению.
//
// ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕТ САМОГО РЕШАТЕЛЯ.
// Раньше в этом файле лежала вторая, независимая реализация метода контурных
// расходов на TypeScript — наследие ранней версии программы. Она давно не
// вызывалась (расчёт полностью ушёл на сервер), но продолжала жить в проекте
// и успела разойтись с серверной моделью: в ней не было естественной тяги,
// иначе считался спад характеристики вентилятора за паспортным пределом,
// отличались границы температур и минимальное сопротивление.
//
// Мёртвый код с ДРУГИМИ формулами опаснее отсутствующего: при чтении проекта
// создаётся впечатление, будто расчётов два и они могут давать разные цифры,
// а при правке легко починить не тот файл. Реализация удалена — остались
// только описания типов: интерфейсу нужно знать форму ответа сервера.
//
// Если понадобится сверить методику — смотреть backend/airflow/index.py.
// ─────────────────────────────────────────────────────────────────────────────
import { type TopoBranch, type TopoNode } from "./topology";

/**
 * Замечание по итогам расчёта — то, что программа сообщает пользователю:
 * разорванная топология, дисбаланс в узле, вентилятор вне паспортной зоны
 * и тому подобное.
 */
export interface SolveDiagnostic {
  level: "error" | "warning" | "info";
  category: "topology" | "node_balance" | "branch_flow" | "fan" | "convergence";
  message: string;
  objectId?: string;
  value?: number;
}

/**
 * Результат расчёта сети — форма ответа функции airflow.
 *
 * Поля branches и nodes могут приходить пустыми: рассчитанные величины
 * программа записывает прямо в объекты схемы, а отсюда берёт только сводку
 * о ходе расчёта (сошлось / за сколько итераций / с какой невязкой).
 */
export interface SolveResult {
  /** Расчёт сошёлся */
  ok: boolean;
  /** Сколько итераций потребовалось */
  iterations: number;
  /** Максимальная невязка по расходу, м³/с */
  maxDeltaQ: number;
  /** Максимальная невязка по давлению, Па */
  maxDeltaH: number;
  /** Ветви с рассчитанными величинами */
  branches: TopoBranch[];
  /** Узлы с рассчитанными величинами */
  nodes: TopoNode[];
  /** Журнал расчёта — построчно, как показывается пользователю */
  log: string[];
  /** Число независимых контуров в сети */
  cyclesCount: number;
  /** Замечания и предупреждения по итогам расчёта */
  diagnostics: SolveDiagnostic[];
}

/** Настройки расчёта, передаваемые на сервер */
export interface SolveOptions {
  /** Предельное число итераций */
  maxIter?: number;
  /** Допуск по расходу, м³/с */
  tolerance?: number;
  /** Допуск по давлению, Па */
  tolPressure?: number;
}
