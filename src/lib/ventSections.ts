export function makeVentSection(partial?: Partial<VentSection>): VentSection {
  return {
    id: Math.random().toString(36).slice(2, 10),
    number: "",
    name: "",
    type: "stoping",
    color: "#3182ce",
    branchIds: [],
    reserveFactor: 0,
    leakFactor: 0,
    isReserve: false,
    comment: "",
    ...partial,
  };
}

