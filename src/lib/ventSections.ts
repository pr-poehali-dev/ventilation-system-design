/**
 * Какие факторы потребности применимы к типу забоя.
 * Нужно, чтобы карточка забоя не показывала лишние поля: в конвейерной
 * выработке не ведут взрывные работы, в камере служебного назначения — тоже.
 *
 * Фактор «по минимальной скорости» здесь не указан: он применяется всегда
 * и считается из сечения выработки, ручного ввода не требует.
 *
 * ВАЖНО: это влияет ТОЛЬКО на отображение полей. Расчёт (airDemand.ts)
 * по-прежнему считает все факторы — если данные заданы, они учтутся.
 */
export interface FaceFactorSet {
  /** Расход по числу людей */
  people: boolean;
  /** Разбавление газов взрывных работ */
  blast: boolean;
  /** Проветривание дизельного оборудования */
  diesel: boolean;
}

export const FACE_TYPE_FACTORS: Record<FaceType, FaceFactorSet> = {
  none:        { people: false, blast: false, diesel: false },
  // Очистной и подготовительный забой, тупиковая выработка — полный набор
  stoping:     { people: true,  blast: true,  diesel: true  },
  development: { people: true,  blast: true,  diesel: true  },
  deadend:     { people: true,  blast: true,  diesel: true  },
  // Камеры служебного назначения: взрывных работ нет, но техника бывает
  // (гараж, ремонтная камера, зарядная)
  chamber:     { people: true,  blast: false, diesel: true  },
  // Конвейерная выработка: транспорт, взрывных работ и дизеля нет
  conveyor:    { people: true,  blast: false, diesel: false },
};

/**
 * Нормы расхода воздуха — редактируемый справочник проекта.
 * Значения по умолчанию соответствуют ФНиП № 505 и сложившейся практике
 * проектирования рудников.
 */
export interface VentNorms {
  // ─── По людям ─────────────────────────────────────────────────────────
  /** Норма расхода воздуха на одного человека, м³/мин (ФНиП: 6) */
  airPerPerson: number;

  // ─── По газам взрывных работ ──────────────────────────────────────────
  /** Газовыделение при взрывании по УГЛЮ, л на 1 кг ВВ (100) */
  gasPerKgCoal: number;
  /** Газовыделение при взрывании по ПОРОДЕ, л на 1 кг ВВ (40) */
  gasPerKgRock: number;
  /** Нормативное время проветривания после взрыва, мин (30) */
  blastVentTime: number;
  /** Коэффициент обводнённости выработки (1.0 — сухая) */
  wateringFactor: number;
  /** Предельно допустимая концентрация условного оксида углерода, % (0.008) */
  coLimit: number;

  // ─── По дизельному оборудованию ───────────────────────────────────────
  /**
   * Норма подачи свежего воздуха на единицу мощности ДВС, м³/мин на кВт.
   * Классическое значение 6,8 м³/мин·кВт (пересчёт с 5 м³/мин на 1 л.с.).
   * Норма установлена в 1970-х и считается завышенной для современной
   * техники — предприятия согласовывают сниженные значения, поэтому
   * параметр редактируемый.
   */
  airPerKwDiesel: number;
  /** Коэффициент одновременности при 1 машине */
  simult1: number;
  /** Коэффициент одновременности при 2 машинах */
  simult2: number;
  /** Коэффициент одновременности при 3 и более машинах */
  simult3: number;

  // ─── Скорости движения воздуха ────────────────────────────────────────
  /** Минимальная скорость в очистных и подготовительных выработках, м/с */
  vMinFace: number;
  /** Минимальная скорость в прочих выработках, м/с */
  vMinOther: number;
  /** Максимальная скорость в выработках, м/с */
  vMaxDrift: number;
  /** Максимальная скорость в стволах с подъёмом людей, м/с */
  vMaxShaft: number;

  // ─── Коэффициенты запаса и утечек ─────────────────────────────────────
  /** Общий коэффициент запаса по руднику */
  reserveFactor: number;
  /** Общий коэффициент утечек воздуха */
  leakFactor: number;
  /** Доля потребности для резервных забоев/участков (0.5 = половина) */
  reserveShare: number;
}

