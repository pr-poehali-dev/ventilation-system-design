/**
 * Коэффициент одновременности работы дизельных машин по их количеству.
 * n=1 → 1.0; n=2 → 0.85; n≥3 → 0.6 (снижается, т.к. машины не работают
 * на полной мощности одновременно).
 */
export function simultaneityFactor(count: number, norms: VentNorms): number {
  if (count <= 1) return norms.simult1;
  if (count === 2) return norms.simult2;
  return norms.simult3;
}