// ─────────────────────────────────────────────────────────────────────────────
// ventSections.ts — Участки рудника и нормы расхода воздуха.
//
// Нормативная база: ФНиП «Правила безопасности при ведении горных работ и
// переработке твёрдых полезных ископаемых» (приказ Ростехнадзора № 505
// от 08.12.2020), п. 155:
//   расчёт количества воздуха производится ПОЗАБОЙНО — суммированием
//   потребностей отдельных забоев, действующих выработок, блоков, участков,
//   панелей, общешахтных камер служебного назначения, с введением
//   обоснованных коэффициентов запаса.
//
// Отсюда две сущности:
//   • ЗАБОЙ  — данные на самой ветви (поля vent* в TopoBranch);
//   • УЧАСТОК — именованная группа ветвей (VentSection, этот файл),
//     по которой выполняется суммирование.
//
// Нормы вынесены в отдельный редактируемый справочник (VentNorms): предприятия
// согласовывают собственные значения (особенно по дизельной технике), поэтому
// жёстко зашивать числа в расчёт нельзя.
// ─────────────────────────────────────────────────────────────────────────────

/** Тип участка/группы выработок */
export type VentSectionType =
  | "stoping"      // очистной участок (блок, панель, камера очистная)
  | "development"  // подготовительный участок
  | "chamber"      // общешахтные камеры служебного назначения
  | "panel"        // панель
  | "block"        // блок
  | "other";       // прочее

export const SECTION_TYPE_LABEL: Record<VentSectionType, string> = {
  stoping:     "Очистной участок",
  development: "Подготовительный участок",
  chamber:     "Камеры служебного назначения",
  panel:       "Панель",
  block:       "Блок",
  other:       "Прочее",
};

export const SECTION_TYPE_OPTIONS: { value: VentSectionType; label: string }[] =
  (Object.keys(SECTION_TYPE_LABEL) as VentSectionType[])
    .map(v => ({ value: v, label: SECTION_TYPE_LABEL[v] }));

/** Участок рудника — группа выработок для позабойного суммирования */
export interface VentSection {
  id: string;
  /** Номер участка (для отчёта и сортировки) */
  number: string;
  /** Наименование участка */
  name: string;
  /** Тип участка */
  type: VentSectionType;
  /** Цвет для выделения на схеме */
  color: string;
  /** Привязанные ветви (как в позициях ПЛА) */
  branchIds: string[];
  /**
   * Коэффициент запаса участка. 0 = взять общий из справочника норм.
   * ФНиП п.155 требует «обоснованных коэффициентов запаса», которые могут
   * отличаться по участкам.
   */
  reserveFactor: number;
  /** Коэффициент утечек участка. 0 = взять общий из справочника норм. */
  leakFactor: number;
  /**
   * Резервный участок — в норматив включается половина расчётной потребности
   * (участок не работает постоянно).
   */
  isReserve: boolean;
  /** Примечание */
  comment: string;
}

