// ─────────────────────────────────────────────────────────────────────────────
// ventDuctLeakTables.ts — коэффициент утечек воздуха Kу.т для гибких рукавов
// KolaVent Flex по данным изготовителя (ООО «КолаВент», «О системе расчётов»).
//
// ЧТО ЭТО ЗА КОЭФФИЦИЕНТ.
// Kу.т ≥ 1 показывает, во сколько раз вентилятор должен подать больше воздуха,
// чем требуется в забое: Q_вент = Kу.т · Q_забой. Коэффициент доставки —
// величина обратная: K_дост = 1 / Kу.т.
//
// ОТКУДА ДАННЫЕ.
//   • Ставы до 200 м — формула изготовителя: Kу.т = 1 + (L/100)·0,0085;
//   • ставы длиннее 200 м при длине звена от 20 м — таблицы 1.1, 1.2 и 1.3.
// Таблица выбирается по количеству воздуха, подаваемого в забой:
//   до 15 м³/с — 1.1, свыше 15 до 50 м³/с — 1.2, свыше 50 м³/с — 1.3.
//
// ПРОЧЕРКИ В ТАБЛИЦАХ. Прочерк означает, что изготовитель не подтверждает
// сочетание «длина + диаметр + расход»: рукав такого диаметра на такой длине
// не обеспечит нужную подачу. Это не «нет данных», а прямое указание взять
// больший диаметр, поэтому расчёт по такому сочетанию не выполняется.
// ─────────────────────────────────────────────────────────────────────────────

/** Строка таблицы: диаметр рукава и значения Kу.т по колонкам расхода */
interface LeakRow {
  /** Диаметр рукава, м */
  d: number;
  /** Kу.т по колонкам; null — прочерк в таблице изготовителя */
  v: (number | null)[];
}

interface LeakTable {
  /** Обозначение таблицы у изготовителя */
  label: string;
  /** Верхние границы колонок расхода, м³/с */
  flows: number[];
  /**
   * Нижние границы колонок расхода, м³/с.
   * В таблице 1.1 колонки заданы диапазонами (до 2,5; 2,51–5; 5,01–7,5; …),
   * поэтому расход внутри диапазона берёт готовое значение колонки без
   * интерполяции. В таблицах 1.2 и 1.3 колонки — точки, там границы совпадают
   * с flows и работает интерполяция между соседними колонками.
   */
  lows: number[];
  /** Строки по длине става: длина, м → строки по диаметрам */
  rows: Record<number, LeakRow[]>;
}

