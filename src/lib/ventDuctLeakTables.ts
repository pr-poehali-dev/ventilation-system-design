/** Все диаметры, для которых у изготовителя есть данные по утечкам, мм */
export const KOLAVENT_LEAK_DIAMETERS = [600, 800, 1000, 1200, 1400, 1600, 1800, 2000, 2400];

export interface LeakLookup {
  /** Коэффициент утечек Kу.т (≥ 1) */
  k: number;
  /** Коэффициент доставки воздуха K_дост = 1 / Kу.т */
  delivery: number;
  /** Откуда взято значение */
  source: "formula" | "table";
  /** Обозначение таблицы изготовителя, если значение взято из таблицы */
  table?: string;
  /** Пояснение для инженера: как именно получено значение */
  note: string;
}

export interface LeakLookupFail {
  k: null;
  /** Причина, почему значение получить нельзя */
  reason: string;
  /** Диаметры (мм), при которых на этой длине и расходе данные есть */
  suggest: number[];
}

export type LeakResult = LeakLookup | LeakLookupFail;

/** Линейная интерполяция между двумя точками */
function lerp(x: number, x1: number, y1: number, x2: number, y2: number): number {
  if (x2 === x1) return y1;
  return y1 + ((y2 - y1) * (x - x1)) / (x2 - x1);
}

/**
 * Подбирает таблицы по расходу воздуха в забое.
 *
 * Обычно подходит ровно одна таблица, но на стыках диапазонов их две: расход
 * 50 м³/с есть и в таблице 1.2 (как верхняя граница), и в таблице 1.3 (как
 * первая колонка), а 15 м³/с — граница между 1.1 и 1.2. На стыке возвращаем
 * обе: у них разные наборы диаметров, и рукав, которого нет в одной, может
 * быть в другой. Иначе на ровной цифре 50 м³/с расчёт отказывал бы для ⌀1400,
 * хотя у изготовителя данные для него есть.
 */
function pickTables(flow: number): LeakTable[] {
  if (flow < 15) return [TABLE_1_1];
  if (flow === 15) return [TABLE_1_1, TABLE_1_2];
  if (flow < 50) return [TABLE_1_2];
  if (flow === 50) return [TABLE_1_2, TABLE_1_3];
  return [TABLE_1_3];
}

/**
 * Значение Kу.т в одной строке таблицы по расходу.
 *
 * Между колонками интерполируем. Ключевой момент — ПРОЧЕРКИ по краям строки:
 * если нужный расход попадает на прочерк, значение НЕ подбирается из соседней
 * заполненной колонки. Прочерк означает, что изготовитель это сочетание не
 * подтверждает, и подстановка ближайшего числа маскировала бы недопустимый
 * режим. Крайнюю колонку берём только там, где она реально крайняя в таблице.
 */
function valueByFlow(row: LeakRow, flows: number[], lows: number[], flow: number): number | null {
  const idx: number[] = [];
  row.v.forEach((v, i) => { if (v != null) idx.push(i); });
  if (!idx.length) return null;

  const first = idx[0];
  const last = idx[idx.length - 1];

  // Расход ниже первой заполненной колонки: допустимо, только если эта
  // колонка — первая в таблице (иначе слева прочерк).
  if (flow < lows[first]) return first === 0 ? row.v[first]! : null;
  // Расход выше последней заполненной колонки: допустимо, только если эта
  // колонка — последняя в таблице (иначе справа прочерк).
  if (flow > flows[last]) return last === flows.length - 1 ? row.v[last]! : null;

  for (let i = 0; i < idx.length - 1; i++) {
    const a = idx[i], b = idx[i + 1];
    if (flow >= lows[a] && flow <= flows[b]) {
      if (flow <= flows[a]) return row.v[a]!;
      return lerp(flow, flows[a], row.v[a]!, flows[b], row.v[b]!);
    }
  }
  return row.v[last]!;
}

/** Kу.т для конкретной длины из таблицы (без интерполяции по длине) */
function valueAtLength(t: LeakTable, len: number, dM: number, flow: number): number | null {
  const rows = t.rows[len];
  if (!rows) return null;
  const row = rows.find(r => Math.abs(r.d - dM) < 0.001);
  if (!row) return null;
  return valueByFlow(row, t.flows, t.lows, flow);
}

/** Диаметры (мм), для которых на этой длине и расходе данные есть */
function availableDiameters(t: LeakTable, len: number, flow: number): number[] {
  const lens = Object.keys(t.rows).map(Number).sort((a, b) => a - b);
  const near = lens.reduce((best, l) =>
    Math.abs(l - len) < Math.abs(best - len) ? l : best, lens[0]);
  return (t.rows[near] ?? [])
    .filter(r => valueByFlow(r, t.flows, t.lows, flow) != null)
    .map(r => Math.round(r.d * 1000));
}

/**
 * Коэффициент утечек Kу.т для рукава KolaVent Flex.
 *
 * @param lengthM   длина става, м
 * @param diameterMm внутренний диаметр рукава, мм
 * @param flowFace  количество воздуха, подаваемого в забой, м³/с
 */
export function kolaVentLeak(lengthM: number, diameterMm: number, flowFace: number): LeakResult {
  const L = Math.max(0, lengthM);
  const dM = diameterMm / 1000;
  const q = Math.max(0, flowFace);

  // Ставы до 200 м — формула изготовителя, диаметр в неё не входит.
  if (L <= 200) {
    const k = 1 + (L / 100) * 0.0085;
    return {
      k,
      delivery: 1 / k,
      source: "formula",
      note: `Формула изготовителя для ставов до 200 м: Kу.т = 1 + (${Math.round(L)}/100)·0,0085.`,
    };
  }

  const tables = pickTables(q);

  // Пробуем каждую подходящую таблицу: на стыке диапазонов их две.
  for (const t of tables) {
    const lens = Object.keys(t.rows).map(Number).sort((a, b) => a - b);

    // Точное совпадение по длине
    const exact = valueAtLength(t, L, dM, q);
    if (exact != null) {
      return {
        k: exact,
        delivery: 1 / exact,
        source: "table",
        table: t.label,
        note: `Таблица ${t.label} изготовителя: став ${Math.round(L)} м, рукав ⌀${Math.round(diameterMm)} мм, подача в забой ${q.toFixed(1)} м³/с.`,
      };
    }

    // Длина между строками таблицы — интерполируем по соседним строкам,
    // где для этого диаметра значение есть.
    const below = [...lens].reverse().find(l => l < L && valueAtLength(t, l, dM, q) != null);
    const above = lens.find(l => l > L && valueAtLength(t, l, dM, q) != null);

    if (below != null && above != null) {
      const k = lerp(L, below, valueAtLength(t, below, dM, q)!, above, valueAtLength(t, above, dM, q)!);
      return {
        k,
        delivery: 1 / k,
        source: "table",
        table: t.label,
        note: `Таблица ${t.label}: значение получено между строками ${below} и ${above} м для рукава ⌀${Math.round(diameterMm)} мм.`,
      };
    }
  }

  // Ни одна таблица не дала значения — объясняем причину по основной таблице.
  const t = tables[tables.length - 1];
  const lens = Object.keys(t.rows).map(Number).sort((a, b) => a - b);
  const maxLen = lens[lens.length - 1];

  // Став длиннее последней строки таблицы — за пределы не экстраполируем:
  // утечки растут нелинейно, и такой прогноз изготовитель не подтверждает.
  // Важно не спутать это с прочерком: если в таблице ЕСТЬ строки длиннее
  // нашего става, значит дело не в длине, а в неподтверждённом сочетании
  // диаметра и расхода — иначе инженер получил бы неверную подсказку.
  if (L > maxLen) {
    return {
      k: null,
      reason: `Став ${Math.round(L)} м длиннее последней строки таблицы ${t.label} (${maxLen} м). Изготовитель такую длину не подтверждает.`,
      suggest: availableDiameters(t, L, q),
    };
  }

  // Подсказку собираем по всем подходящим таблицам: на стыке диапазонов
  // нужный диаметр может найтись в соседней.
  const suggest = [...new Set(tables.flatMap(x => availableDiameters(x, L, q)))]
    .sort((a, b) => a - b);

  return {
    k: null,
    reason: `В таблице ${t.label} нет данных для рукава ⌀${Math.round(diameterMm)} мм при ставе ${Math.round(L)} м и подаче ${q.toFixed(1)} м³/с — изготовитель ставит прочерк.`,
    suggest,
  };
}