// ─────────────────────────────────────────────────────────────────────────────
// smokeVisibility.ts — ЕДИНЫЙ расчёт дальности видимости в дыму.
//
// Зачем отдельный модуль:
// раньше видимость считалась в двух местах по РАЗНЫМ формулам —
//   • расчёт пожара (fireCalculator)      : L = 3 / μ
//   • маршруты ВГСЧ (rescueCalculator)    : L = 2 / μ
// Из-за этого одна и та же ветвь могла считаться «чистой» в свойствах пожара
// и «слабо задымлённой» при расчёте выхода отделения: расхождение в 1,5 раза
// на границах зон 5 и 10 м меняло коэффициент k3, а с ним время выхода и
// расход кислорода. Теперь формула ОДНА и живёт здесь.
//
// Физика: закон Бугера–Ламберта–Бера. Дальность видимости обратно
// пропорциональна оптической плотности дыма μ (м⁻¹):
//
//     L = K / μ
//
// K — безразмерный коэффициент различимости объекта. Принят K = 3 для
// светящихся объектов (шахтный светильник, аварийное освещение) — именно этот
// сценарий соответствует передвижению людей и горноспасателей по выработке.
// ─────────────────────────────────────────────────────────────────────────────

/** Коэффициент различимости в законе Бугера (светящийся объект). */
export const VIS_K = 3;

/**
 * Потолок расчётной видимости, м. Нужен, чтобы при почти нулевой плотности
 * дыма не получать бесконечность. Должен быть НЕ МЕНЬШЕ максимального порога
 * видимости в настройках пожара (1000 м), иначе порог выше потолка проверить
 * невозможно — все слабо задымлённые ветви показывали бы одно значение.
 */
export const VIS_MAX_M = 1000;

/** Плотность дыма ниже этой считается чистым воздухом (м⁻¹). */
export const CLEAN_AIR_DENS = 0.001;

// ─── Границы нормативных зон задымления (Инструкция № 520) ───────────────────
// Коэффициент снижения скорости передвижения горноспасателей k3:
//   k3 = 1,00 — чистый воздух        (Рв > 10 м)
//   k3 = 1,43 — слабое задымление    (Рв 5–10 м)
//   k3 = 2,00 — густое задымление    (Рв < 5 м)
export const VIS_ZONE_CLEAN_M = 10;
export const VIS_ZONE_SMOKY_M = 5;

export type SmokeZone = "clean" | "smoky_low" | "smoky_high";

/**
 * Дальность видимости в дыму, м. Единая формула для всей программы.
 * @param smokeDensity оптическая плотность дыма, м⁻¹
 */
export function visibilityFromDensity(smokeDensity: number): number {
  if (!(smokeDensity > 0)) return VIS_MAX_M;
  return Math.min(VIS_MAX_M, VIS_K / smokeDensity);
}

/**
 * Оптическая плотность дыма, соответствующая заданной дальности видимости.
 * Обратная к visibilityFromDensity — используется для порога обрыва фронта.
 * @param visibility_m дальность видимости, м
 */
export function densityFromVisibility(visibility_m: number): number {
  if (!(visibility_m > 0)) return Infinity;
  return VIS_K / visibility_m;
}

/**
 * Зона задымления по плотности дыма — для коэффициента k3 (Инструкция № 520).
 * Считается через ту же формулу видимости, что и всё остальное.
 */
export function zoneFromDensity(smokeDensity: number): SmokeZone {
  if (smokeDensity <= CLEAN_AIR_DENS) return "clean";
  const vis = visibilityFromDensity(smokeDensity);
  if (vis >= VIS_ZONE_CLEAN_M) return "clean";
  if (vis >= VIS_ZONE_SMOKY_M) return "smoky_low";
  return "smoky_high";
}

