// ─────────────────────────────────────────────────────────────────────────────
// Оформление подписей у условных обозначений: замерных станций и вентиляторов.
//
// На крупных схемах такие подписи теряются среди выработок: белая обводка
// текста сливается с фоном и с соседними подписями расходов. Поэтому под них
// подкладывается цветная плашка — зелёная у замерных станций и синяя у
// вентиляторов, чтобы замер и оборудование различались с первого взгляда.
//
// Модуль общий для всех способов отрисовки: интерактивная схема (SVG и Canvas),
// экспорт в SVG и вывод на печать. Цвет по умолчанию должен быть одинаковым
// везде, иначе печатная схема разойдётся с экранной.
// ─────────────────────────────────────────────────────────────────────────────

/** Цвет подложки индикаторов ЗС по умолчанию — зелёный. */
export const MS_IND_BG_DEFAULT = "#16a34a";

/**
 * Цвет подложки подписи вентилятора по умолчанию — синий.
 * Намеренно отличается от зелёного у замерных станций: на схеме сразу видно,
 * где замер расхода, а где оборудование.
 */
export const FAN_IND_BG_DEFAULT = "#2563eb";

/** Значение «без подложки». */
export const MS_IND_BG_NONE = "none";

/**
 * Итоговый цвет подложки индикаторов ЗС.
 * undefined (поле ещё не задавали) → зелёный по умолчанию.
 * "none" → подложка не рисуется, возвращаем null.
 */
export function msIndBg(color: string | undefined, fallback = MS_IND_BG_DEFAULT): string | null {
  const c = color ?? fallback;
  return c === MS_IND_BG_NONE ? null : c;
}

/** Цвет подложки подписи вентилятора (по умолчанию синий). */
export function fanIndBg(color: string | undefined): string | null {
  return msIndBg(color, FAN_IND_BG_DEFAULT);
}

/**
 * Цвет текста поверх подложки. На тёмной плашке текст белый, без плашки —
 * прежний тёмно-синий. Яркость считаем по восприятию (глаз чувствительнее
 * к зелёному), иначе на жёлтой подложке белый текст становится нечитаемым.
 */
export function msIndTextColor(bg: string | null): string {
  if (!bg) return "#1a2a4a";
  const m = /^#?([0-9a-f]{6})$/i.exec(bg.trim());
  if (!m) return "#ffffff";
  const v = parseInt(m[1], 16);
  const r = (v >> 16) & 255, g = (v >> 8) & 255, b = v & 255;
  const lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return lum > 0.6 ? "#1a2a4a" : "#ffffff";
}

