-- Признак: место уже закреплено за конкретной установкой браузера.
-- До этого место опознавалось по общим характеристикам ПК (экран, часовой
-- пояс, ОС), которые совпадают у разных компьютеров, — чужой ПК получал
-- лицензию без ввода ключа. Перенос на новый отпечаток выполняется один раз,
-- после чего этот флаг закрывает такую возможность.
ALTER TABLE license_seats
  ADD COLUMN IF NOT EXISTS install_bound BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN license_seats.install_bound IS
  'TRUE — место закреплено за конкретной установкой (браузер), перенос по общим характеристикам ПК запрещён';
